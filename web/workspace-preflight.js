'use strict';
window.snapmaticPreflight=(facts,title,caption,tags,raw=false)=>{
 const bytes=new TextEncoder().encode(caption).length, chars=Array.from(caption).length, units=caption.length;
 const titleChars=Array.from(title).length;
 const hashtags=(caption+' '+tags).match(/#[\p{L}\p{N}_]+/gu)?.length||0;
 const f=facts?.format||{}, streams=facts?.streams||[], v=streams.find(x=>x.codec_type==='video')||{}, a=streams.find(x=>x.codec_type==='audio')||{};
 const n=x=>Number(x)>0?Number(x):null, d=n(f.duration), size=n(f.size), w=n(v.width), h=n(v.height);
 const [p,q]=(v.avg_frame_rate||'').split('/').map(Number), fps=p>0&&q>0?p/q:null;
 const videoRate=n(v.bit_rate),audioRate=n(a.bit_rate),sample=n(a.sample_rate), channels=n(a.channels);
 const mp4=f.format_name?.split(',').includes('mp4');
 const rows={youtube:[],instagram:[],tiktok:[]};const rawAv1=raw&&v.codec_name==='av1';
 function check(id,group,valid,label){rows[id].push({group,state:valid==null?'UNKNOWN':valid?'PASS':group==='Advisory'?'WARN':'FAIL',label});}
 check('youtube','API',size&&size<=256e9,'File size ≤256 GB');
 check('youtube','API',titleChars>0&&titleChars<=100&&!/[<>]/.test(title),titleChars+'/100 title characters (no < or >)');
 check('youtube','API',bytes<=5000&&!/[<>]/.test(caption),bytes+'/5000 description UTF-8 bytes (no < or >)');
 check('youtube','Shorts',d&&d<=180,'Shorts duration ≤180 s');
 check('youtube','Shorts',w&&h&&h>=w,'Square or vertical Shorts');
 check('youtube','Snapmatic',d&&d>=1,'Shorts project minimum 1 s');
 check('instagram','API',d&&d>=3&&d<=900,'Reels duration 3–900 s');
 check('instagram','API',size&&size<=300e6,'Reels file size ≤300 MB');
 check('instagram','API',f.format_name?mp4:null,'MP4 or MOV container');
 check('instagram','API',v.codec_name?['h264','hevc'].includes(v.codec_name):null,'H.264 or HEVC');
 if(rawAv1)Object.assign(rows.instagram.at(-1),{state:'NEEDS H.264 TRANSCODE',label:'Raw AV1 preview; not eligible to upload'});
 check('instagram','API',fps&&fps>=23&&fps<=60,'23–60 fps (probed average)');
 check('instagram','API',w&&w<=1920,'Width ≤1920 px');
 check('instagram','API',videoRate>25e6?false:null,'VBR ≤25 Mbps (average alone cannot verify peak/encoding mode)');
 check('instagram','API',a.codec_name?(a.codec_name==='aac'&&sample&&channels&&sample<=48000&&channels<=2):null,'AAC, ≤48 kHz, mono/stereo');
 check('instagram','Advisory',audioRate&&Math.abs(audioRate-128000)<=16000,'AAC bitrate near 128 kbps nominal target');
 check('instagram','API',chars<=2200&&hashtags<=30,chars+'/2200 caption characters · '+hashtags+'/30 hashtags');
 check('instagram','Advisory',w&&h&&w*16===h*9,'Recommended 9:16 framing');
 check('instagram','Advisory',d&&d<=180,'Reels over 180 s may be less discoverable');
 check('tiktok','Export format',d&&d<=600,'Local export duration ≤600 s');
 check('tiktok','Export format',size&&size<=180*1024*1024,'Local export file size ≤180 MiB');
 check('tiktok','Export format',f.format_name?mp4:null,'MP4 container');
 check('tiktok','Export format',v.codec_name?v.codec_name==='h264':null,'H.264 video');
 if(rawAv1)Object.assign(rows.tiktok.at(-1),{state:'NEEDS H.264 TRANSCODE',label:'Raw AV1 preview; not eligible to upload'});
 check('tiktok','Export format',fps&&fps>=23&&fps<=60,'23–60 fps (probed average)');
 check('tiktok','Export format',w&&h&&[w,h].every(x=>x>=360&&x<=4096),'Both sides 360–4096 px');
 check('tiktok','Snapmatic',d&&d>=3,'Local export minimum 3 s');
 check('tiktok','Advisory',d&&d<=180,'Over 180 s: confirm support in the TikTok app before posting');
 check('tiktok','Advisory',units<=2200,units+'/2200 UTF-16 units (local caption advisory)');
 check('tiktok','Export review',null,'Requires an individually approved and independently verified render.');
 return rows;
};