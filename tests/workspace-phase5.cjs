const assert=require('node:assert/strict');
const p=require('../web/workspace-phase5.js');
const fps={streams:[{codec_type:'video',avg_frame_rate:'30/1',r_frame_rate:'30/1'}]};
assert.equal(p.step(0,3,1,fps),1/30);
assert.equal(p.step(1,3,-1,fps),29/30);
assert.equal(p.step(0,3,-1,fps),0);
assert.equal(p.step(2.99,3,1,fps),89/30);
assert.equal(p.step(0,3,1,{streams:[{codec_type:'video',avg_frame_rate:'30/1',r_frame_rate:'60/1'}]}),null);
assert.equal(p.loop(.5,1,2,1),.5);
assert.equal(p.loop(.5,1,2,.9),null);
assert.equal(p.loop(.5,3,2,1),null);
assert.deepEqual(p.metadata({},2),{peaks:null,speech:null});
const sample={waveform_peaks:[.1,.5,.6,.5,0,.5,.2,.4],speech_segments:[{start_ms:0,end_ms:200}]};
assert.strictEqual(p.metadata(sample,2).speech,sample.speech_segments);
assert.strictEqual(p.metadata(sample,2).peaks,sample.waveform_peaks);
assert.equal(p.metadata({speech_segments:[{start_ms:0,end_ms:200},{start_ms:100,end_ms:300}]},2).speech,null);
p.setAnchor('a');p.range(['a','b','c'],'c');assert.equal(p.batch.size,3);
assert.equal(p.review('publish',['a','b']),0);
assert.equal(p.review('Archive',['a','b']),2);
assert.equal(p.decisions.get('a'),'Archive');assert.equal(p.decisions.has('c'),false);
